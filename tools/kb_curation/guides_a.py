def _s(en, tr, action="none", target=None, vt=None, anchor=None):
    return dict(text=(en, tr), action=action, target=target, vendor_table=vt, anchor=anchor)


def _b(id, when, en, tr, steps, verify=(), next_on_fail=None):
    return dict(id=id, when=list(when), text=(en, tr), steps=list(steps), verify=list(verify), next_on_fail=next_on_fail)


