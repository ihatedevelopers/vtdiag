using System.Text.Json.Serialization;
using VTD.Contracts.Fixes;

namespace VTD.Contracts.Knowledge;

/// <summary>Kind of conflicting software (the 12 kinds in <c>research/conflicts.json</c>).</summary>
public enum ConflictKind
{
    /// <summary>Antivirus.</summary>
    [JsonStringEnumMemberName("antivirus")] Antivirus,

    /// <summary>VPN.</summary>
    [JsonStringEnumMemberName("vpn")] Vpn,

    /// <summary>RGB / peripheral vendor software.</summary>
    [JsonStringEnumMemberName("rgb_vendor")] RgbVendor,

    /// <summary>Overlay or hook.</summary>
    [JsonStringEnumMemberName("overlay")] Overlay,

    /// <summary>Driver.</summary>
    [JsonStringEnumMemberName("driver")] Driver,

    /// <summary>Tweak / debloat tool.</summary>
    [JsonStringEnumMemberName("tweak_tool")] TweakTool,

    /// <summary>Virtualization.</summary>
    [JsonStringEnumMemberName("virtualization")] Virtualization,

    /// <summary>Other anti-cheat.</summary>
    [JsonStringEnumMemberName("anticheat")] Anticheat,

    /// <summary>Audio enhancer.</summary>
    [JsonStringEnumMemberName("audio")] Audio,

    /// <summary>Network optimizer / booster.</summary>
    [JsonStringEnumMemberName("network_optimizer")] NetworkOptimizer,

    /// <summary>Monitoring tool.</summary>
    [JsonStringEnumMemberName("monitoring")] Monitoring,

    /// <summary>Other.</summary>
    [JsonStringEnumMemberName("other")] Other,
}

/// <summary>
/// A known conflicting software entry, imported mechanically from <c>research/conflicts.json</c> (113 entries) by
/// <c>tools/kb_builder.py</c>. One generic provider materializes its signals for every entry
/// (<c>conflict.&lt;id&gt;.installed|running|service_present|driver_loaded|adapter_present|crash_module|audio_endpoint|feature_enabled|registry_present|file_present</c>),
/// and each entry yields a low-prior <see cref="RuleKind.Generated"/> hypothesis unless a full rule supersedes it.
/// File: <c>kb/conflicts/&lt;kind&gt;.json</c>. Schema: <c>kb/schema/conflict.schema.json</c>.
/// </summary>
[Sensitivity(Sensitivity.None)]
public sealed record ConflictDef
{
    /// <summary>Stable id (snake_case, as in conflicts.json), for example <c>nahimic</c>, <c>realtek_2_5gbe</c>.</summary>
    public required string Id { get; init; }

    /// <summary>Human name (English, not a string key: it is a product name).</summary>
    public required string Name { get; init; }

    /// <summary>Kind.</summary>
    public required ConflictKind Kind { get; init; }

    /// <summary>Detection fingerprints.</summary>
    public required ConflictDetect Detect { get; init; }

    /// <summary>String keys of the observed effects.</summary>
    public IReadOnlyList<string> EffectKeys { get; init; } = [];

    /// <summary>Remedy.</summary>
    public required ConflictFix Fix { get; init; }

    /// <summary>Confidence of the entry.</summary>
    public required ConfidenceLevel Confidence { get; init; }

    /// <summary>Category used for the generated hypothesis prior.</summary>
    public ProblemCategory Category { get; init; } = ProblemCategory.Other;

    /// <summary>Symptoms the generated hypothesis explains.</summary>
    public IReadOnlyList<string> Symptoms { get; init; } = [];

    /// <summary>Date-limited outbreak.</summary>
    public WaveDef? Wave { get; init; }

    /// <summary>Provenance.</summary>
    public ConflictEvidence? Evidence { get; init; }

    /// <summary>String key of maintainer notes.</summary>
    public string? NotesKey { get; init; }
}

/// <summary>Detection fingerprints. All matching is ordinal and case-insensitive; regexes are NonBacktracking with a timeout.</summary>
[Sensitivity(Sensitivity.None)]
public sealed record ConflictDetect
{
    /// <summary>Process image names.</summary>
    public IReadOnlyList<string> ProcessNames { get; init; } = [];

    /// <summary>Service names (not display names).</summary>
    public IReadOnlyList<string> ServiceNames { get; init; } = [];

    /// <summary>Kernel driver file names.</summary>
    public IReadOnlyList<string> DriverNames { get; init; } = [];

    /// <summary>Module names seen as faulting modules in Riot crashes (for example <c>ProductInfo.dll</c>).</summary>
    public IReadOnlyList<string> ModuleNames { get; init; } = [];

    /// <summary>Regex on uninstall DisplayName.</summary>
    public string? UninstallDisplayNameRegex { get; init; }

    /// <summary>Regex on network adapter description.</summary>
    public string? NetworkAdapterRegex { get; init; }

    /// <summary>Regex on audio endpoint name (prefer the locale-free HFP flag where possible).</summary>
    public string? AudioEndpointRegex { get; init; }

    /// <summary>Registry values (<c>HKLM\…\Key\ValueName</c> or keys); read through pack registry collectors generated by kb_builder.</summary>
    public IReadOnlyList<string> RegistryKeys { get; init; } = [];

    /// <summary>File or folder paths; read through pack file collectors generated by kb_builder.</summary>
    public IReadOnlyList<string> FilePaths { get; init; } = [];

    /// <summary>Windows optional feature names.</summary>
    public IReadOnlyList<string> WindowsFeatures { get; init; } = [];
}

/// <summary>Remedy for a conflict.</summary>
[Sensitivity(Sensitivity.None)]
public sealed record ConflictFix
{
    /// <summary>String key of the plain-language action.</summary>
    public required string ActionKey { get; init; }

    /// <summary>The remedy is reversible.</summary>
    public required bool Reversible { get; init; }

    /// <summary>Risk.</summary>
    public required RiskLevel Risk { get; init; }

    /// <summary>KB fix ids that implement it (often an entity-bound template such as <c>fix.svc.disable_conflict_service</c>).</summary>
    public IReadOnlyList<string> FixIds { get; init; } = [];

    /// <summary>Guide ids (uninstall flows are guides: the uninstaller runs unelevated in the player's context).</summary>
    public IReadOnlyList<string> GuideIds { get; init; } = [];
}

/// <summary>Provenance of a conflict entry.</summary>
[Sensitivity(Sensitivity.None)]
public sealed record ConflictEvidence
{
    /// <summary>Reddit mentions.</summary>
    public int RedditMentions { get; init; }

    /// <summary>Mentions in solved threads.</summary>
    public int SolvedMentions { get; init; }

    /// <summary>Example thread ids.</summary>
    public IReadOnlyList<string> ExampleThreadIds { get; init; } = [];

    /// <summary>Web sources.</summary>
    public IReadOnlyList<string> WebSources { get; init; } = [];
}

/// <summary>
/// One row of the error-code table (from <c>research/error_codes.json</c>, 57 codes). Codes go through this table with a
/// per-cause strength; codes found in logs weigh more than codes the player typed (typos, mis-copies); a route code
/// short-circuits (VAN 152 to appeal, console/VM/Mac out of scope, VAL 43/57/59 "try another account").
/// File: <c>kb/codes/*.json</c>. Schema: <c>kb/schema/code.schema.json</c>.
/// </summary>
[Sensitivity(Sensitivity.None)]
public sealed record ErrorCodeDef
{
    /// <summary>Stable id, for example <c>van-9003</c>, <c>val-group-account</c>.</summary>
    public required string Id { get; init; }

    /// <summary>Canonical normalized codes this row covers (<c>VAN 9003</c>; groups like <c>VAL 31</c>, <c>VAL 43</c>...).
    /// Normalization (A2): upper-case invariant, "VAN9003", "van-9003", "VAN: 9003" all become <c>VAN 9003</c>.</summary>
    public required IReadOnlyList<string> Codes { get; init; }

    /// <summary>Category from the research data (for example <c>vanguard_requirement</c>, <c>ban</c>, <c>val_account</c>).</summary>
    public required string Category { get; init; }

    /// <summary>String key of the official meaning.</summary>
    public required string MeaningKey { get; init; }

    /// <summary>Route verdict; when set, ranking short-circuits and no fix is offered.</summary>
    public RouteKind? Route { get; init; }

    /// <summary>Causes this code points at, each with its own strength.</summary>
    public IReadOnlyList<CodeCause> PointsTo { get; init; } = [];

    /// <summary>Official Riot support URLs (shown, never auto-opened from plans).</summary>
    public IReadOnlyList<string> OfficialUrls { get; init; } = [];

    /// <summary>Question to ask when the code was only typed (for example "does another account work on this PC?").</summary>
    public string? AskIfTyped { get; init; }

    /// <summary>Confidence of the mapping.</summary>
    public ConfidenceLevel Confidence { get; init; } = ConfidenceLevel.Medium;
}

/// <summary>A cause an error code points at.</summary>
[Sensitivity(Sensitivity.None)]
public sealed record CodeCause
{
    /// <summary>Rule id.</summary>
    public required string Hypothesis { get; init; }

    /// <summary>Log-odds when the code was found in logs or crash reports.</summary>
    public required double Logged { get; init; }

    /// <summary>Log-odds when the code was only typed by the player (must be at most <see cref="Logged"/>).</summary>
    public required double Typed { get; init; }
}

/// <summary>Result of looking up a typed or logged code.</summary>
public sealed record ErrorCodeMatch
{
    /// <summary>The table row.</summary>
    public required ErrorCodeDef Def { get; init; }

    /// <summary>The normalized code that matched.</summary>
    public required string Normalized { get; init; }

    /// <summary>The input matched exactly after normalization (false = fuzzy/alias match).</summary>
    public required bool Exact { get; init; }
}
